def test_fixtures_come_from_the_pinned_mathlive() -> None:
    package = json.loads((Path(__file__).parents[2] / "web" / "package.json").read_text())
    assert FIXTURES["mathlive"] == package["dependencies"]["mathlive"]
    assert set(CASES) == set(EXPECTED)


@pytest.mark.parametrize("case_id", sorted(EXPECTED))
def test_lowering(case_id: str) -> None:
    latex = CASES[case_id]["latex"]
    want = EXPECTED[case_id]
    if want.startswith("!"):
        with pytest.raises(InputError) as info:
            lower(latex)
        assert info.value.message.startswith(want[1:])
    else:
        assert lower(latex) == want


def test_ascii_math_is_lossy() -> None:
    """Why the checker doesn't read MathLive's ascii-math: words split, structure lost."""
    assert CASES["dne"]["ascii"] == "D N E"
    assert CASES["none"]["ascii"] == "n o n e"
    assert CASES["mixed-number"]["ascii"] == "3(1)/(2)"  # 3 1/2 indistinguishable from 3*(1/2)
    assert CASES["sin-squared"]["ascii"] == "sin ^2x"
    assert CASES["empty-set"]["ascii"] == "O/"
    assert CASES["sqrt-over-2-times-sin"]["ascii"] == "(sqrt(x))/(2)sin (x)"


@pytest.mark.parametrize(
    ("latex", "plain"),
    [
        (r"\dfrac{1}{x}", "((1)/(x))"),
        (r"\left\lvert x\right\rvert", "abs(x)"),
        (r"\operatorname{arcsec}\left(x\right)", "arcsec(x)"),
        (r"\operatorname{sgn}x", "sign(x)"),
        (r"\cos^{2}x+\sin^2x", "cos(x)^(2)+sin(x)^(2)"),
        (r"\ln\left(\left|x\right|\right)", "ln(abs(x))"),
        (r"\sin\frac{\pi}{2}", "sin((( pi )/(2)))"),
        (r"\sin\sqrt{x}", "sin(sqrt(x))"),
        (r"x_{1}+x_2", "x_1+x_2"),
        (r"\alpha\beta", "alpha * beta"),
        (r"a\,b", "ab"),
        (r"\begin{pmatrix}1\\ 2\end{pmatrix}", "[[1], [2]]"),
        (r"\left\langle 1,2\right\rangle", "<1,2>"),
        (r"x\ne1", "x!=1"),
        (r"x\geq0", "x>=0"),
        (r"\left(0,1\right\rbrack", "(0,1]"),
        (r"\mathrm{e}^x", "e^(x)"),
        (r"\imaginaryI", "i"),
    ],
)
def test_more_lowerings(latex: str, plain: str) -> None:
    assert lower(latex) == plain


@pytest.mark.parametrize(
    "latex",
    [
        r"\pm2",
        r"\frac{1}{\placeholder{}}",
        r"\int x",
        r"\sum_{n=1}^5 n",
        r"\sin",
        r"\left\|x\right\|",
        r"\begin{vmatrix}1\end{vmatrix}",
        r"x_{\frac12}",
        r"\text{3}",
        r"{",
        "",
    ],
)
def test_lowering_errors(latex: str) -> None:
    with pytest.raises(InputError):
        lower(latex)


def test_latex_limits() -> None:
    with pytest.raises(InputError) as info:
        lower("x+" * MAX_LATEX_CHARS)
    assert info.value.kind == "limit"
    with pytest.raises(InputError) as info:
        lower("{" * 50 + "x" + "}" * 50)
    assert info.value.kind == "limit"
